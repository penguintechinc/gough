"""Contract test: the discovery-agent's golden payload must match DiscoverRequest.

The fixture is generated by the Go payload builder (services/discovery-agent
internal/discover, TestBuildRequest_Golden). This test loads that same file from
the repo, validates it against the hub schema, asserts no key is silently
dropped by Pydantic's extra=ignore, then posts it through the real route and
checks the persisted hardware_json.
"""

from __future__ import annotations

import copy
import json
import uuid
from pathlib import Path
from typing import Any
from unittest.mock import MagicMock, patch

import pytest
from app.api._schemas.nodes import (
    AcceleratorInfo,
    DiscoverRequest,
    NicInfo,
    NumaTopology,
    SmartAttribute,
)
from pydantic import ValidationError

# Re-use the nodes_app / dal wiring from the discover endpoint suite.
from tests.api import test_nodes as _nodes_suite

dal = _nodes_suite.dal
nodes_app = _nodes_suite.nodes_app

GOLDEN_PATH = (
    Path(__file__).resolve().parents[3]
    / "discovery-agent"
    / "internal"
    / "discover"
    / "testdata"
    / "discover_request.golden.json"
)

_NESTED: dict[str, type] = {
    "smart_attributes": SmartAttribute,
    "nics": NicInfo,
    "accelerators": AcceleratorInfo,
}


def _load_golden() -> dict[str, Any]:
    """Return the Go-generated golden payload as a dict.

    Raises:
        AssertionError: when the fixture is missing or is not a JSON object.
    """
    assert GOLDEN_PATH.is_file(), f"golden fixture missing: {GOLDEN_PATH}"
    data = json.loads(GOLDEN_PATH.read_text(encoding="utf-8"))
    assert isinstance(data, dict), "golden fixture must be a JSON object"
    return data


def _unknown_keys(payload: dict[str, Any]) -> list[str]:
    """List every key the hub schema would silently ignore, including nested items.

    Args:
        payload: Decoded discovery request body.

    Returns:
        Dotted paths of keys absent from the corresponding Pydantic model.
    """
    unknown = [k for k in payload if k not in DiscoverRequest.model_fields]
    for field, model in _NESTED.items():
        items = payload.get(field) or []
        for idx, item in enumerate(items):
            unknown += [
                f"{field}[{idx}].{k}" for k in item if k not in model.model_fields
            ]
    numa = payload.get("numa_topology")
    if isinstance(numa, dict):
        unknown += [
            f"numa_topology.{k}" for k in numa if k not in NumaTopology.model_fields
        ]
    return unknown


def test_golden_fixture_has_no_keys_the_hub_ignores() -> None:
    """Every emitted key must be a declared field, at top level and nested."""
    assert _unknown_keys(_load_golden()) == []


def test_golden_fixture_validates_against_discover_request() -> None:
    """The Go payload must parse under DiscoverRequest without coercion surprises."""
    model = DiscoverRequest.model_validate(_load_golden())
    assert model.firmware_type == "uefi"
    assert model.bmc_tls_status == "ok"
    assert model.numa_topology is not None and model.numa_topology.nodes == 2


def test_golden_fixture_rejects_unknown_bmc_status() -> None:
    """A status outside the shared enum must fail validation, not pass through."""
    bad = _load_golden()
    bad["bmc_tls_status"] = "bmc_bogus"
    with pytest.raises(ValidationError):
        DiscoverRequest.model_validate(bad)


def test_golden_fixture_rejects_malformed_cert_sha() -> None:
    """bmc_cert_sha256 must be 64 lowercase hex characters."""
    bad = _load_golden()
    bad["bmc_cert_sha256"] = "XYZ"
    with pytest.raises(ValidationError):
        DiscoverRequest.model_validate(bad)


@pytest.mark.asyncio
async def test_golden_payload_posts_and_persists_hardware_json(nodes_app, dal) -> None:
    """POST the golden body through the real route; assert 2xx and persisted fields."""
    payload = copy.deepcopy(_load_golden())
    payload["dmi_uuid"] = str(uuid.uuid4())

    principal = MagicMock()
    principal.sub = "bootstrap:aa:bb:cc:dd:ee:01"
    with patch(
        "app.security.credentials.validate_one_time_bootstrap_token",
        return_value=principal,
    ), patch(
        "app.clients.spire.SpireClient.register_workload", return_value="entry-c1"
    ):
        async with nodes_app.test_client() as client:
            resp = await client.post(
                "/api/v1/nodes/discover",
                json=payload,
                headers={"Authorization": "Bearer valid-token"},
            )

    assert 200 <= resp.status_code < 300, await resp.get_data(as_text=True)
    node_id = json.loads(await resp.get_data(as_text=True))["data"]["node_id"]

    rows = dal(dal.nodes.id == node_id).select()
    assert len(rows) == 1
    hw = rows[0].hardware_json
    assert hw["firmware_type"] == "uefi"
    assert hw["hostname"] == "gough-node-01"
    assert hw["sys_vendor"] == "Dell Inc."
    assert hw["product_name"] == "PowerEdge R640"
    assert hw["bios_version"] == "2.19.1"
    assert hw["bmc_tls_status"] == "ok"
    assert hw["bmc_cert_sha256"] == "ab" * 32
    assert hw["lshw"]["class"] == "system"
    assert len(hw["nics"]) == 2 and hw["nics"][0]["is_primary"] is True
    assert len(hw["smart_attributes"]) == 2
    assert hw["smart_attributes"][0]["device"] == "sda"
    assert len(hw["accelerators"]) == 3
    assert hw["numa_topology"]["nodes"] == 2
