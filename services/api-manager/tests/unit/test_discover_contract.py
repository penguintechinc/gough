"""Contract test: the discovery-agent's golden payload must match DiscoverRequest.

The fixture is generated by the Go payload builder (services/discovery-agent
internal/discover, TestBuildRequest_Golden). This test loads that same file from
the repo, validates it against the hub schema, asserts no key is silently
dropped by Pydantic's extra=ignore, then posts it through the real route and
checks the persisted hardware_json.
"""

from __future__ import annotations

import copy
import json
import uuid
from pathlib import Path
from types import SimpleNamespace
from typing import Any
from unittest.mock import MagicMock, patch

import pytest
from pydantic import ValidationError

from app.api._schemas.nodes import (
    AcceleratorInfo,
    DiscoverRequest,
    NicInfo,
    NumaTopology,
    SmartAttribute,
)

# Re-use the nodes_app / dal wiring from the discover endpoint suite.
from tests.api.test_nodes import dal, nodes_app  # noqa: F401

GOLDEN_PATH = (
    Path(__file__).resolve().parents[3]
    / "discovery-agent"
    / "internal"
    / "discover"
    / "testdata"
    / "discover_request.golden.json"
)

_NESTED: dict[str, type] = {
    "smart_attributes": SmartAttribute,
    "nics": NicInfo,
    "accelerators": AcceleratorInfo,
}


def _load_golden() -> dict[str, Any]:
    """Return the Go-generated golden payload as a dict.

    Raises:
        AssertionError: when the fixture is missing or is not a JSON object.
    """
    assert GOLDEN_PATH.is_file(), f"golden fixture missing: {GOLDEN_PATH}"
    data = json.loads(GOLDEN_PATH.read_text(encoding="utf-8"))
    assert isinstance(data, dict), "golden fixture must be a JSON object"
    return data


def _unknown_keys(payload: dict[str, Any]) -> list[str]:
    """List every key the hub schema would silently ignore, including nested items.

    Args:
        payload: Decoded discovery request body.

    Returns:
        Dotted paths of keys absent from the corresponding Pydantic model.
    """
    unknown = [k for k in payload if k not in DiscoverRequest.model_fields]
    for field, model in _NESTED.items():
        items = payload.get(field) or []
        for idx, item in enumerate(items):
            unknown += [f"{field}[{idx}].{k}" for k in item if k not in model.model_fields]
    numa = payload.get("numa_topology")
    if isinstance(numa, dict):
        unknown += [f"numa_topology.{k}" for k in numa if k not in NumaTopology.model_fields]
    return unknown


def test_golden_fixture_has_no_keys_the_hub_ignores() -> None:
    """Every emitted key must be a declared field, at top level and nested."""
    assert _unknown_keys(_load_golden()) == []


def test_golden_fixture_validates_against_discover_request() -> None:
    """The Go payload must parse under DiscoverRequest without coercion surprises."""
    model = DiscoverRequest.model_validate(_load_golden())
    assert model.firmware_type == "uefi"
    assert model.bmc_tls_status == "ok"
    assert model.numa_topology is not None and model.numa_topology.nodes == 2


def test_golden_fixture_rejects_unknown_bmc_status() -> None:
    """A status outside the shared enum must fail validation, not pass through."""
    bad = _load_golden()
    bad["bmc_tls_status"] = "bmc_bogus"
    with pytest.raises(ValidationError):
        DiscoverRequest.model_validate(bad)


def test_golden_fixture_rejects_malformed_cert_sha() -> None:
    """bmc_cert_sha256 must be 64 lowercase hex characters."""
    bad = _load_golden()
    bad["bmc_cert_sha256"] = "XYZ"
    with pytest.raises(ValidationError):
        DiscoverRequest.model_validate(bad)


@pytest.mark.asyncio
async def test_golden_payload_posts_and_persists_hardware_json(nodes_app, dal) -> None:  # noqa: F811
    """POST the golden body through the real route; assert 2xx and persisted fields."""
    payload = copy.deepcopy(_load_golden())
    payload["dmi_uuid"] = str(uuid.uuid4())

    principal = MagicMock()
    principal.sub = "bootstrap:aa:bb:cc:dd:ee:01"
    with patch(
        "app.security.credentials.validate_one_time_bootstrap_token",
        return_value=principal,
    ), patch("app.clients.spire.SpireClient.register_workload", return_value="entry-c1"):
        async with nodes_app.test_client() as client:
            resp = await client.post(
                "/api/v1/nodes/discover",
                json=payload,
                headers={"Authorization": "Bearer valid-token"},
            )

    assert 200 <= resp.status_code < 300, await resp.get_data(as_text=True)
    node_id = json.loads(await resp.get_data(as_text=True))["data"]["node_id"]

    rows = dal(dal.nodes.id == node_id).select()
    assert len(rows) == 1
    hw = rows[0].hardware_json
    assert hw["firmware_type"] == "uefi"
    assert hw["hostname"] == "gough-node-01"
    assert hw["sys_vendor"] == "Dell Inc."
    assert hw["product_name"] == "PowerEdge R640"
    assert hw["bios_version"] == "2.19.1"
    assert hw["bmc_tls_status"] == "ok"
    assert hw["bmc_cert_sha256"] == "ab" * 32
    assert hw["lshw"]["class"] == "system"
    assert len(hw["nics"]) == 2 and hw["nics"][0]["is_primary"] is True
    assert len(hw["smart_attributes"]) == 2
    assert hw["smart_attributes"][0]["device"] == "sda"
    assert len(hw["accelerators"]) == 3
    assert hw["numa_topology"]["nodes"] == 2


async def _discover_response(nodes_app, bmc_trust) -> dict[str, Any]:
    """POST the golden body with ``_bmc_trust_for_node`` stubbed; return the response ``data``."""
    payload = copy.deepcopy(_load_golden())
    payload["dmi_uuid"] = str(uuid.uuid4())
    principal = MagicMock()
    principal.sub = "bootstrap:aa:bb:cc:dd:ee:01"
    with patch(
        "app.security.credentials.validate_one_time_bootstrap_token", return_value=principal
    ), patch("app.clients.spire.SpireClient.register_workload", return_value="entry-c1"), patch(
        "app.api.nodes._bmc_trust_for_node", return_value=bmc_trust
    ):
        async with nodes_app.test_client() as client:
            resp = await client.post(
                "/api/v1/nodes/discover",
                json=payload,
                headers={"Authorization": "Bearer valid-token"},
            )
    assert resp.status_code == 201, await resp.get_data(as_text=True)
    return json.loads(await resp.get_data(as_text=True))["data"]


@pytest.mark.asyncio
async def test_discover_response_carries_bmc_trust_when_hub_has_it(nodes_app, dal) -> None:  # noqa: F811
    """The authenticated discover response delivers the BMC address and pin."""
    data = await _discover_response(nodes_app, ("10.1.2.3", "cd" * 32))
    assert data["bmc_address"] == "10.1.2.3"
    assert data["bmc_cert_sha256"] == "cd" * 32


@pytest.mark.asyncio
async def test_discover_response_bmc_fields_null_when_unknown(nodes_app, dal) -> None:  # noqa: F811
    """No BMC on file: both keys are present and null (stable response contract)."""
    data = await _discover_response(nodes_app, (None, None))
    assert data["bmc_address"] is None and data["bmc_cert_sha256"] is None


def test_discover_response_schema_accepts_bmc_fields() -> None:
    """DiscoverResponse models the optional BMC fields and defaults them to None."""
    from app.api._schemas.nodes import DiscoverResponse

    base = dict(
        node_id=1, state="probed", spire_join_token=None,
        control_tunnel_endpoint="grpcs://h:8443", control_tunnel_spiffe_id="spiffe://x/y",
    )
    assert DiscoverResponse(**base).bmc_address is None
    full = DiscoverResponse(**base, bmc_address="h", bmc_cert_sha256="ab" * 32)
    assert (full.bmc_address, full.bmc_cert_sha256) == ("h", "ab" * 32)


def _db_with_bmc(row: Any, tables: tuple[str, ...] = ("nodes", "node_bmc")) -> MagicMock:
    """DAL stand-in whose node_bmc lookup returns ``row``."""
    db = MagicMock()
    db.tables = list(tables)
    db.return_value.select.return_value.first.return_value = row
    return db


@pytest.mark.parametrize(
    ("row", "tables", "expected"),
    [
        (None, ("node_bmc",), (None, None)),
        (SimpleNamespace(endpoint="x", cert_fingerprint=None), ("nodes",), (None, None)),
        (SimpleNamespace(endpoint="https://10.1.2.3:443", cert_fingerprint=":".join(["AB"] * 32)),
         ("node_bmc",), ("10.1.2.3", "ab" * 32)),
        (SimpleNamespace(endpoint="bmc01.lab", cert_fingerprint=None), ("node_bmc",), ("bmc01.lab", None)),
        (SimpleNamespace(endpoint="10.0.0.1", cert_fingerprint="AB:CD"), ("node_bmc",), ("10.0.0.1", None)),
        (SimpleNamespace(endpoint="10.0.0.1 root=/dev/sda", cert_fingerprint=None), ("node_bmc",), (None, None)),
        (SimpleNamespace(endpoint="", cert_fingerprint=None), ("node_bmc",), (None, None)),
        (SimpleNamespace(endpoint="http://", cert_fingerprint=None), ("node_bmc",), (None, None)),
    ],
)
def test_bmc_trust_for_node(row: Any, tables: tuple[str, ...], expected: tuple[Any, Any]) -> None:
    """Only well-formed stored BMC data is returned; the pin never travels without an address."""
    from app.api.nodes import _bmc_trust_for_node

    with patch("app.api.nodes.get_db", return_value=_db_with_bmc(row, tables)):
        assert _bmc_trust_for_node(7) == expected
