#!/usr/bin/env bash
# Deploy the gough hub to the dal2alpha kube context via Helm only (no Kustomize).
# Images are built by make docker-build, pushed to ghcr.io here, and pulled in-cluster.
# The gough ghcr packages are public, so the ghcr-pull dockerconfigjson Secret is OPTIONAL:
# it is attached only when it already exists or GHCR_PULL_USER + GHCR_PULL_TOKEN_FILE are set.
#
# Usage:
#   scripts/deploy-alpha.sh               # push images, ensure pull secret (optional), helm upgrade --install
#   scripts/deploy-alpha.sh --clean       # delete namespace gough first, then deploy
#   scripts/deploy-alpha.sh --skip-push   # images already pushed to ghcr.io
# Env: GOUGH_KUBE_CONTEXT (default dal2alpha). Optional GHCR_PULL_USER + GHCR_PULL_TOKEN_FILE
# (read:packages token file) create the ghcr-pull Secret when it does not exist yet; set both or neither.
# Non-interactive: the OIDC keystore and in-cluster secrets are generated by the chart.
set -euo pipefail

readonly KUBE_CONTEXT="${GOUGH_KUBE_CONTEXT:-dal2alpha}"
readonly NAMESPACE="gough"
readonly RELEASE="gough"
readonly CHART_DIR="k8s/helm/gough"
readonly VALUES_FILE="k8s/helm/gough/alpha.yml"
readonly PULL_SECRET="ghcr-pull"
# Image names come ONLY from the Makefile (exported); docker-build tags exactly these refs.
: "${ALPHA_IMAGE_REGISTRY:?ALPHA_IMAGE_REGISTRY not set - run via make deploy-alpha}"
: "${ALPHA_IMAGE_PREFIX:?ALPHA_IMAGE_PREFIX not set - run via make deploy-alpha}"
: "${ALPHA_TAG:?ALPHA_TAG not set - run via make deploy-alpha}"
readonly IMAGE_REPO_BASE="$ALPHA_IMAGE_REGISTRY/$ALPHA_IMAGE_PREFIX"
readonly IMAGE_TAG="$ALPHA_TAG"
readonly SERVICES=(api-manager webui worker-ipxe)

CLEAN=false
SKIP_PUSH=false
USE_PULL_SECRET=false

log()  { printf '%s\n' "$*"; }
die()  { printf 'ERROR: %s\n' "$*" >&2; exit 1; }

usage() {
    sed -n '2,12p' "$0" | sed 's/^# \{0,1\}//'
}

parse_args() {
    while [[ $# -gt 0 ]]; do
        case "$1" in
            --clean)     CLEAN=true ;;
            --skip-push) SKIP_PUSH=true ;;
            -h|--help)   usage; exit 0 ;;
            *)           die "unknown argument: $1" ;;
        esac
        shift
    done
}

require_tool() {
    command -v "$1" >/dev/null 2>&1 || die "$1 not found in PATH"
}

preflight() {
    require_tool helm
    require_tool kubectl
    require_tool docker
    local contexts
    contexts="$(kubectl config get-contexts -o name)"
    grep -qx "$KUBE_CONTEXT" <<<"$contexts" \
        || die "kube context '$KUBE_CONTEXT' does not exist"
    for svc in "${SERVICES[@]}"; do
        docker image inspect "$IMAGE_REPO_BASE/$svc:$IMAGE_TAG" >/dev/null \
            || die "image missing: $IMAGE_REPO_BASE/$svc:$IMAGE_TAG (run make docker-build first; this script does not build)"
    done
    log "preflight: helm, kubectl, docker present; context '$KUBE_CONTEXT' exists; ${#SERVICES[@]} images found"
}

push_images() {
    if [[ $SKIP_PUSH == true ]]; then
        log "push: skipped (--skip-push)"
        return
    fi
    for svc in "${SERVICES[@]}"; do
        log "push: $IMAGE_REPO_BASE/$svc:$IMAGE_TAG"
        docker push "$IMAGE_REPO_BASE/$svc:$IMAGE_TAG" \
            || die "docker push failed: $IMAGE_REPO_BASE/$svc:$IMAGE_TAG (check: docker login ghcr.io)"
    done
}

ensure_namespace() {
    if [[ $CLEAN == true ]]; then
        log "clean: deleting namespace $NAMESPACE on $KUBE_CONTEXT"
        kubectl --context "$KUBE_CONTEXT" delete namespace "$NAMESPACE" --ignore-not-found=true --wait=true
    fi
    kubectl --context "$KUBE_CONTEXT" get namespace "$NAMESPACE" >/dev/null 2>&1 \
        || kubectl --context "$KUBE_CONTEXT" create namespace "$NAMESPACE"
    kubectl --context "$KUBE_CONTEXT" label namespace "$NAMESPACE" \
        pod-security.kubernetes.io/enforce=restricted --overwrite >/dev/null
}

# Sets USE_PULL_SECRET. Pull secret is optional (packages are public): used if it already exists,
# or created when both GHCR_PULL_USER and GHCR_PULL_TOKEN_FILE are set. The token is read from a file
# and piped to kubectl via stdin: it never appears in argv, environment exports, or log output.
ensure_pull_secret() {
    if kubectl --context "$KUBE_CONTEXT" -n "$NAMESPACE" get secret "$PULL_SECRET" >/dev/null 2>&1; then
        log "pull-secret: $PULL_SECRET present in $KUBE_CONTEXT/$NAMESPACE"
        USE_PULL_SECRET=true
        return
    fi
    if [[ -z "${GHCR_PULL_USER:-}" && -z "${GHCR_PULL_TOKEN_FILE:-}" ]]; then
        log "pull-secret: none (ghcr packages are public)"
        USE_PULL_SECRET=false
        return
    fi
    [[ -n "${GHCR_PULL_USER:-}" && -n "${GHCR_PULL_TOKEN_FILE:-}" ]] \
        || die "set both GHCR_PULL_USER and GHCR_PULL_TOKEN_FILE to create $PULL_SECRET (only one is set)"
    [[ "$GHCR_PULL_USER" =~ ^[A-Za-z0-9-]+$ ]] || die "GHCR_PULL_USER contains invalid characters"
    [[ -r "$GHCR_PULL_TOKEN_FILE" ]] || die "GHCR_PULL_TOKEN_FILE is not a readable file"
    local token auth json
    token="$(tr -d '\r\n' < "$GHCR_PULL_TOKEN_FILE")"
    [[ -n "$token" ]] || die "GHCR_PULL_TOKEN_FILE is empty"
    auth="$(printf '%s:%s' "$GHCR_PULL_USER" "$token" | base64 | tr -d '\n')"
    json="$(printf '{"auths":{"ghcr.io":{"username":"%s","password":"%s","auth":"%s"}}}' \
        "$GHCR_PULL_USER" "$token" "$auth")"
    unset token auth
    printf '%s' "$json" | kubectl --context "$KUBE_CONTEXT" -n "$NAMESPACE" create secret generic "$PULL_SECRET" \
        --type=kubernetes.io/dockerconfigjson --from-file=.dockerconfigjson=/dev/stdin >/dev/null
    unset json
    USE_PULL_SECRET=true
    log "pull-secret: created $PULL_SECRET in $KUBE_CONTEXT/$NAMESPACE"
}

helm_deploy() {
    local pull_args=()
    if [[ $USE_PULL_SECRET == true ]]; then
        pull_args=(--set "global.imagePullSecrets[0].name=$PULL_SECRET")
    fi
    helm dependency update "$CHART_DIR"
    helm upgrade --install "$RELEASE" "$CHART_DIR" \
        -f "$VALUES_FILE" \
        --set-string "global.imageRegistry=$IMAGE_REPO_BASE" \
        --set-string "global.imageTag=$IMAGE_TAG" \
        ${pull_args[@]+"${pull_args[@]}"} \
        -n "$NAMESPACE" \
        --create-namespace \
        --kube-context "$KUBE_CONTEXT" \
        --wait --timeout 10m
    log "helm: release $RELEASE deployed to $KUBE_CONTEXT/$NAMESPACE"
}

main() {
    parse_args "$@"
    cd "$(dirname "$0")/.."
    preflight
    push_images
    ensure_namespace
    ensure_pull_secret
    helm_deploy
}

main "$@"
